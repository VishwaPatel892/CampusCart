async function seed() {
  console.log("Connecting to MongoDB...");
  await mongoose.connect(MONGODB_URI);
  console.log("Connected to MongoDB successfully.\n");

  let addedCount = 0;
  let skippedCount = 0;

  for (const item of sampleProducts) {
    const existing = await Product.findOne({ demoKey: item.demoKey });
    if (existing) {
      skippedCount++;
    } else {
      await Product.create(item);
      addedCount++;
    }
  }

  console.log("==========================================");
  console.log(`SEED COMPLETED:`);
  console.log(`• New demo products inserted: ${addedCount}`);
  console.log(`• Already existing demo products skipped: ${skippedCount}`);
  console.log(`• Total demo inventory available: ${addedCount + skippedCount}`);
  console.log("==========================================");

  await mongoose.disconnect();
  process.exit(0);
}

seed().catch((err) => {
  console.error("Seeding error:", err);
  process.exit(1);
});

